"""Generates test/fixtures.dart: SignalR frames in the messagepack+brotli format.

The Dart brotli package only decodes, so compressed fixtures are produced here.

    pip install msgpack brotli
    python benchmark/generate_fixtures.py
"""

from pathlib import Path

import brotli
import msgpack


def frame(message: list) -> bytes:
    body = msgpack.packb(message, use_bin_type=True)
    size, prefix = len(body), bytearray()
    while True:
        part = size & 0x7F
        size >>= 7
        if size:
            part |= 0x80
        prefix.append(part)
        if not size:
            break
    return bytes(prefix) + body


def compressed(value) -> bytes:
    return brotli.compress(msgpack.packb(value, use_bin_type=True), quality=5)


ODDS = {
    "eventId": 1001,
    "home": "Team A",
    "away": "Team B",
    "markets": [
        {
            "id": 7,
            "name": "Total 2.5",
            "outcomes": [
                {"name": "Over", "odds": 1.85},
                {"name": "Under", "odds": 1.95},
            ],
        }
    ],
}

FIXTURES = {
    "streamItemCompressed": frame([2, {}, "1", 1, compressed(ODDS)]),
    "streamItemPlain": frame([2, {}, "1", 0, ODDS]),
    "invocationCompressed": frame(
        [1, {"trace": "abc"}, None, "OddsUpdated", 1, compressed([ODDS])]
    ),
    "completionCompressed": frame([3, {}, "2", 3, 1, compressed(ODDS)]),
    "completionVoid": frame([3, {}, "3", 2]),
    "batch": frame([6])
    + frame([2, {}, "1", 1, compressed(ODDS)])
    + frame([99, "future"]),
}


def main() -> None:
    lines = [
        "// Generated by benchmark/generate_fixtures.py. Do not edit by hand.",
        "",
        "import 'dart:typed_data';",
        "",
    ]
    for name, data in FIXTURES.items():
        lines.append(f"final {name} = Uint8List.fromList(const [")
        numbers = [str(b) for b in data]
        for i in range(0, len(numbers), 16):
            lines.append("  " + ", ".join(numbers[i : i + 16]) + ",")
        lines += ["]);", ""]

    target = Path(__file__).resolve().parent.parent / "test" / "fixtures.dart"
    target.write_text("\n".join(lines))
    print(f"Wrote {target}")


if __name__ == "__main__":
    main()
